let currentLanguage = localStorage.getItem("novelLanguage") || "my";

function t(key) {
  return (I18N[currentLanguage] && I18N[currentLanguage][key]) || I18N.en[key] || key;
}

function applyStaticTranslations() {
  document.documentElement.lang = currentLanguage === "my" ? "my" : "en";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    const value = t(key);
    if (el.dataset.i18nHtml === "true") el.innerHTML = value;
    else el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(el => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  const button = document.getElementById("languageBtn");
  if (button) {
    button.textContent = t("language");
    button.setAttribute("aria-label", currentLanguage === "en" ? "မြန်မာဘာသာသို့ ပြောင်းရန်" : "Switch to English");
  }
}

function setLanguage(lang) {
  currentLanguage = lang === "my" ? "my" : "en";
  localStorage.setItem("novelLanguage", currentLanguage);
  applyStaticTranslations();
  document.dispatchEvent(new CustomEvent("languagechange", { detail: { language: currentLanguage } }));
}

function toggleLanguage() {
  setLanguage(currentLanguage === "en" ? "my" : "en");
}

document.addEventListener("DOMContentLoaded", () => {
  const button = document.getElementById("languageBtn");
  if (button) button.addEventListener("click", toggleLanguage);
  applyStaticTranslations();
});

window.I18N = I18N;
window.t = t;
window.getLanguage = () => currentLanguage;
window.setLanguage = setLanguage;
